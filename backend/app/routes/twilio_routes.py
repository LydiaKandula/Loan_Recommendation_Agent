class InitiateCallRequest(BaseModel):
    to_number:      str
    user_name:      str   = "there"
    loan_type:      str   = "loan"
    bank:           str   = ""
    emi:            float = 0.0
    # Full loan profile — filled from the loan application form
    loan_amount:    float = 0.0
