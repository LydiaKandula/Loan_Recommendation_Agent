# ── Helpers ───────────────────────────────────────────────────────────────────

def _auth_id(authorization: Optional[str] = Header(None)) -> Optional[int]:
    if not authorization or not authorization.startswith("Bearer "):
        return None
    payload = decode_token(authorization.split(" ", 1)[1])
    return payload["id"] if payload else None


def _require_base() -> str:
    if not PUBLIC_BASE_URL or PUBLIC_BASE_URL.strip() == "":
        raise HTTPException(500,
            "PUBLIC_BASE_URL not set in .env — add your ngrok https URL")
    return PUBLIC_BASE_URL.rstrip("/")


def _xml(text: str) -> str:
    """Clean markdown and escape for TwiML XML."""
    clean = (str(text or "")
             .replace("**", "").replace("*", "")
             .replace("#",  "").replace("`", "")
             .replace("\n", " ").strip())
    return html.escape(clean, quote=True)


def _spoken(text: str) -> str:
    """
    Make text more natural for voice:
    - EMI → E.M.I  (forces letter-by-letter reading in Sarvam)
    - ₹  → rupees
    - %  → percent
    """
    return (text
            .replace("EMI",  "E.M.I")
            .replace("emi",  "E.M.I")
            .replace("₹",    "rupees ")
            .replace("Rs.",  "rupees ")
            .replace("%",    " percent")
            .replace("p.a.", "per annum"))


async def _sarvam_tts(text: str, language: str = "en") -> bytes | None:
    """
    Call Sarvam Bulbul v3 TTS. Returns raw WAV bytes or None if unavailable.
    """
    if not SARVAM_API_KEY:
        return None

    lang_map = {"en": "en-IN", "hi": "hi-IN", "te": "te-IN"}
    payload  = {
        "text":                 _spoken(text)[:2500],
        "target_language_code": lang_map.get(language, "en-IN"),
        "speaker":              "ritu",        # best female voice
        "model":                "bulbul:v3",
        "pace":                 0.9,           # slightly slower = clearer on phone
        "speech_sample_rate":   8000,          # 8 kHz is ideal for phone audio
        "output_audio_codec":   "wav",
    }
    try:
        async with httpx.AsyncClient(timeout=12) as client:
            resp = await client.post(
                "https://api.sarvam.ai/text-to-speech",
                headers={
                    "api-subscription-key": SARVAM_API_KEY,
                    "Content-Type":         "application/json",
                },
                json=payload,
            )
        resp.raise_for_status()
        audios = resp.json().get("audios", [])
        if audios:
            return base64.b64decode(audios[0])
    except Exception as e:
        print(f"Sarvam TTS error: {e}")
    return None


async def _sarvam_stt(audio_bytes: bytes, language: str = "en-IN") -> str | None:
    """
    Call Sarvam speech-to-text. Returns transcript string or None.
    """
    if not SARVAM_API_KEY:
        return None
    try:
        async with httpx.AsyncClient(timeout=15) as client:
            resp = await client.post(
                "https://api.sarvam.ai/speech-to-text",
                headers={"api-subscription-key": SARVAM_API_KEY},
                files={"file": ("audio.wav", audio_bytes, "audio/wav")},
                data={"language_code": language, "model": "saarika:v2"},
            )
        resp.raise_for_status()
        return resp.json().get("transcript", "").strip()
    except Exception as e:
        print(f"Sarvam STT error: {e}")
    return None


async def _build_twiml_with_audio(
    text: str,
    gather_url: str,
    call_sid: str,
    turn: str,
    base: str,
    language: str = "en",
    final: bool = False,
) -> str:
    """
    Generate Sarvam audio for `text`, cache it, and return TwiML that uses
    <Play> if audio was generated, falling back to <Say> otherwise.
    """
    wav = await _sarvam_tts(text, language)

    if wav:
        if call_sid not in _audio_cache:
            _audio_cache[call_sid] = {}
        _audio_cache[call_sid][turn] = wav
        audio_url = f"{base}/calls/audio/{call_sid}/{turn}"
        say_block = f'<Play>{audio_url}</Play>'
    else:
        say_block = f'<Say voice="alice" language="en-IN">{_xml(text)}</Say>'

    if final:
        return f"""<?xml version="1.0" encoding="UTF-8"?>
<Response>
  {say_block}
  <Hangup/>
</Response>"""

    return f"""<?xml version="1.0" encoding="UTF-8"?>
<Response>
  {say_block}
  <Gather input="speech" action="{gather_url}" method="POST"
          speechTimeout="3" language="en-IN" timeout="10">
  </Gather>
  <Hangup/>
</Response>"""


def _build_loan_context(log: CallLog) -> str:
    """Build a rich system-prompt context string from the stored loan profile."""
    lines = ["You are a professional loan advisor on a phone call."]
    if log.customer_name:
        lines.append(f"Customer name: {log.customer_name}")
    if log.loan_type:
        lines.append(f"Loan type: {log.loan_type}")
    if log.loan_amount:
        lines.append(f"Loan amount: rupees {int(log.loan_amount):,}")
    if log.loan_tenure:
        lines.append(f"Tenure: {log.loan_tenure} months")
    if log.monthly_income:
        lines.append(f"Monthly income: rupees {int(log.monthly_income):,}")
    if log.credit_score:
        lines.append(f"Credit score: {log.credit_score}")
    if log.recommended_bank:
        lines.append(f"Recommended bank: {log.recommended_bank}")
    if log.recommended_emi:
        lines.append(f"Monthly E.M.I: rupees {int(log.recommended_emi):,}")
    lines.append(
        "Use this profile to give personalised answers. "
        "Do NOT ask the customer for information you already have. "
        "Speak in 1-2 short sentences. Plain English only. "
        "No markdown, no bullet points, no special characters."
    )
    return " ".join(lines)


